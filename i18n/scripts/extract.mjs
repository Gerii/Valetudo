/*
 * Scans frontend + backend sources and writes i18n/<lang>/missing.json with everything that
 * still needs a translation (see AGENTS.md).
 *
 * Usage: node i18n/scripts/extract.mjs [--lang de] [--prune]
 *   --prune  removes dictionary entries whose source string no longer exists
 */
import path from "node:path";
import {analyze, I18N_DIR, readJson, rel, writeJson} from "./lib.mjs";

const args = process.argv.slice(2);
const lang = args.includes("--lang") ? args[args.indexOf("--lang") + 1] : "de";
const prune = args.includes("--prune");
const langDir = path.join(I18N_DIR, lang);

const result = analyze(lang);

const strip = (entries) => {
    return Object.fromEntries(Object.entries(entries).map(([k, v]) => {
        return [k, {kind: v.kind, locations: v.locations}];
    }));
};

const staleOverrides = result.overrides.textResources.filter(r => r.status !== "ok").map(r => {
    return {source: rel(r.source), override: rel(r.override), status: r.status, "upstream-sha256": r.hash};
});

writeJson(path.join(langDir, "missing.json"), {
    $comment: "Generated by i18n/scripts/extract.mjs. Translate these into frontend.json/backend.json (value null = intentionally not translated) and update the listed overrides. See AGENTS.md.",
    frontend: strip(result.missingFrontend),
    backend: strip(result.missingBackend),
    overrides: staleOverrides
});

if (prune) {
    for (const [file, unused] of [["frontend.json", result.unusedFrontend], ["backend.json", result.unusedBackend]]) {
        const dictPath = path.join(langDir, file);
        const dict = readJson(dictPath, {});
        unused.forEach(k => {
            delete dict[k];
        });
        writeJson(dictPath, dict);
    }
}

console.log(`Missing frontend strings: ${Object.keys(result.missingFrontend).length}`);
console.log(`Missing backend strings:  ${Object.keys(result.missingBackend).length}`);
console.log(`Overrides to (re)do:      ${staleOverrides.length}${staleOverrides.length ? "\n  " + staleOverrides.map(o => `${o.status}: ${o.override}`).join("\n  ") : ""}`);
console.log(`Orphaned overrides:       ${result.overrides.orphanedOverrides.length}${result.overrides.orphanedOverrides.length ? "\n  " + result.overrides.orphanedOverrides.map(rel).join("\n  ") : ""}`);
console.log(`Unused dictionary keys:   ${result.unusedFrontend.length + result.unusedBackend.length}${prune ? " (pruned)" : " (run with --prune to remove)"}`);
if (result.placeholderErrors.length) {
    console.log(`Placeholder mismatches:\n  ${result.placeholderErrors.join("\n  ")}`);
}
console.log(`\nWrote ${rel(path.join(langDir, "missing.json"))}`);
